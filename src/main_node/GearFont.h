static const uint16_t GLYPH_ROWS_3[GEAR_FONT_HEIGHT] = { 0x000, 0x1F8, 0x1FC, 0x00C, 0x00C, 0x00C, 0x00C, 0x1FC, 0x1FC, 0x00C, 0x00C, 0x00C, 0x00C, 0x1FC, 0x1F8, 0x000 };
static const uint16_t GLYPH_ROWS_4[GEAR_FONT_HEIGHT] = { 0x000, 0x000, 0x30C, 0x30C, 0x30C, 0x30C, 0x30C, 0x3FC, 0x1FC, 0x00C, 0x00C, 0x00C, 0x00C, 0x00C, 0x000, 0x000 };

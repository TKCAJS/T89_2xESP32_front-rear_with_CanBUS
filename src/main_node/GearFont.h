static const GearGlyph GEAR_FONT_GLYPHS[] = {
    { '1', 12, GLYPH_ROWS_1 },
    { '2', 12, GLYPH_ROWS_2 },
    { '3', 12, GLYPH_ROWS_3 },
    { '4', 12, GLYPH_ROWS_4 },
    { '5', 12, GLYPH_ROWS_5 },
    { '6', 12, GLYPH_ROWS_6 },
    { 'N', 12, GLYPH_ROWS_N },
    { 'W', 14, GLYPH_ROWS_W },
    { 'D', 12, GLYPH_ROWS_D },
    { 'U', 12, GLYPH_ROWS_U },
    { 'C', 12, GLYPH_ROWS_C },
    { 'F', 12, GLYPH_ROWS_F },
    { '?', 12, GLYPH_ROWS_Q },
};

static const GearGlyph* gearFontFind(char c) {
    for (const auto& g : GEAR_FONT_GLYPHS) {
        if (g.c == c) return &g;
    }
    return nullptr;
}

#endif

static const uint16_t GLYPH_ROWS_N[GEAR_FONT_HEIGHT] = { 0x000, 0x3CC, 0x3CC, 0x3CC, 0x3CC, 0x36C, 0x36C, 0x36C, 0x33C, 0x33C, 0x33C, 0x31C, 0x31C, 0x31C, 0x31C, 0x000 };
